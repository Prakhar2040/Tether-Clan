export interface Lifetime {
  nights: number
  seats: number
  rooms: number
  months: number
  sinceLabel: string
}

const MON = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

export function lifetimeOf(communityId: string, now = new Date()): Lifetime {
  const nights = history[communityId] ?? []
  if (nights.length === 0) return { nights: 0, seats: 0, rooms: 0, months: 0, sinceLabel: '' }
  const first = new Date(`${nights[0][0]}T00:00:00`)
  return {
    nights: nights.length,
    seats: nights.reduce((n, x) => n + x[2], 0),
    rooms: new Set(nights.map((x) => x[1])).size,
    months: (now.getFullYear() - first.getFullYear()) * 12 + (now.getMonth() - first.getMonth()),
    sinceLabel: `${MON[first.getMonth()]} ${first.getFullYear()}`,
  }
}
